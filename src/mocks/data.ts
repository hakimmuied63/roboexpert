// ===== Seller Stats =====
export const getSellerStats = (sellerId: string): SellerStats => {
  const sellerProducts = products.filter(p => p.sellerId === sellerId);
  const sellerOrders = orders.filter(o => o.items.some(i => i.sellerId === sellerId));
  const sellerPayments = payments.filter(p => p.sellerId === sellerId);
  const activeOrders = sellerOrders.filter(o => o.status !== 'delivered' && o.status !== 'cancelled');
  const totalRevenue = sellerPayments.filter(p => p.status === 'paid').reduce((sum, p) => sum + p.amount, 0);
  const pendingPayments = sellerPayments.filter(p => p.status === 'pending').reduce((sum, p) => sum + p.amount, 0);

  return {
    totalProducts: sellerProducts.length,
    activeOrders: activeOrders.length,
    totalRevenue,
    pendingPayments,
    monthlySales: [12400, 18200, 15800, 22100, 19500, 24800, 21300, 28900, 25600, 31200, 27800, 35400],
  };
};

